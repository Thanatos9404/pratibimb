export function Evidence({ data }: { data: LandingData }) {
  const m = data.metrics;
  const f = m?.forecast;
  const parkesAB = f?.parkes?.map((p) => (isNum(p.A) && isNum(p.B) ? p.A + p.B : null));
  return (
    <section id="evidence" className="scroll-mt-24 px-5 py-24 sm:py-32" style={{ background: "linear-gradient(180deg, #f9f8f8 0%, #e9eef4 100%)" }}>
      <SectionHead eyebrow="Evidence" line1="Scored on patients" line2="the model never saw.">
        {m ? `${m.dataset.test_patients} held-out synthetic patients, generated by a richer simulator than the twin itself. Numbers below are read from the engine’s metrics file.` : "Metrics appear once the engine export is present."}
        {data.kind === "mock" && <span className="mt-2 block font-semibold text-[#e5484d]">Mock fixtures: placeholder numbers, not results.</span>}
      </SectionHead>
      <div className="mx-auto mt-14 grid max-w-[1072px] items-center gap-5 lg:grid-cols-3">
        {TASKS.map((t, i) => {
          const x = m?.tasks?.[t.key];
          const op = x?.operating_point;
          const featured = i === 1;
          const body = (
            <div className={cn("h-full rounded-[26px] p-7", featured ? "" : "bg-white")} style={featured ? { background: "linear-gradient(180deg, #b7d5f1 0%, #f4e6da 100%)" } : undefined}>
              <div className="text-[15px] text-body">{t.sub}</div>
              <div className="mt-1 text-[24px] font-bold tracking-[-0.03em]">{t.title}</div>
              <div className="mt-5 flex items-baseline gap-2">
                <span className="text-[48px] leading-none font-bold tracking-[-0.045em]">{isNum(x?.auroc) ? x.auroc.toFixed(2) : DASH}</span>
                <span className="text-[14px] font-medium text-muted-ink">AUROC</span>
              </div>
              <ul className="mt-6 space-y-3 text-[15px]">
                {[
                  ["Median warning", isNum(op?.median_lead_min) ? `${op.median_lead_min} min ahead` : DASH],
                  ["Sensitivity", isNum(op?.sensitivity) ? `${Math.round(op.sensitivity * 100)}%` : DASH],
                  ["Precision", isNum(op?.precision) ? `${Math.round(op.precision * 100)}%` : DASH],
                  ["Alerts per patient-day", isNum(op?.alerts_per_patient_day) ? op.alerts_per_patient_day.toFixed(2) : DASH],
                ].map(([k, v]) => (
                  <li key={k} className="flex items-center justify-between gap-3 border-b border-black/5 pb-3 last:border-0">
                    <span className="text-body">{k}</span>
                    <span className="num font-semibold">{v}</span>
                  </li>
                ))}
              </ul>
            </div>
          );
          return (
            <Reveal key={t.key} delay={i * 0.08}>
              {featured ? (
                <div className="rounded-[30px] bg-[#7fb0e6] p-[3px] shadow-[var(--shadow-soft)] lg:-my-6">{body}</div>
              ) : (
                <div className="rounded-[28px] shadow-[var(--shadow-soft)]">{body}</div>
              )}
            </Reveal>
          );
        })}
      </div>
      <div className="mx-auto mt-10 grid max-w-[1072px] gap-5 sm:grid-cols-3">
        {[
          ["Forecast error at +30 / +60 / +120 min", f ? f.rmse.map((v) => (isNum(v) ? v.toFixed(0) : DASH)).join(" / ") + " mg/dL" : DASH, f ? `RMSE; linear baseline ${f.baseline_rmse.map((v) => (isNum(v) ? v.toFixed(0) : DASH)).join(" / ")}` : ""],
          ["Parkes zones A + B", parkesAB ? parkesAB.map((v) => (v == null ? DASH : `${v.toFixed(1)}%`)).join(" / ") : DASH, "at +30 / +60 / +120 min (Type 2 grid)"],
          ["Twin sync error", isNum(m?.sync?.twin_vs_truth_mard) ? `${m.sync.twin_vs_truth_mard.toFixed(1)}% MARD` : DASH, isNum(m?.sync?.cgm_vs_truth_mard) ? `the CGM sensor itself: ${m.sync.cgm_vs_truth_mard.toFixed(1)}%` : "filtered estimate vs truth"],
        ].map(([a, b, c]) => (
          <Reveal key={a}>
            <div className="h-full rounded-[24px] bg-white/80 p-6 shadow-[var(--shadow-soft)]">
              <div className="text-[13.5px] text-muted-ink">{a}</div>
              <div className="num mt-2 text-[22px] font-bold tracking-[-0.03em]">{b}</div>
              <div className="mt-1 text-[12.5px] text-muted-ink">{c}</div>
            </div>
          </Reveal>
        ))}
      </div>
      {data.real && <RealEvidence r={data.real} />}
      <div className="mt-10 flex justify-center">
        <Link href="/console/model" className="pill-dark">
          Read the model card <ArrowRightIcon className="arrow size-4" />
        </Link>
      </div>
    </section>
  );
}

const fmtList = (xs: (number | null)[], d = 1) => xs.map((v) => (isNum(v) ? v.toFixed(d) : DASH)).join(" / ");

/** Real-data check card: every number from public/demo/real_validation.json. */
function RealEvidence({ r }: { r: NonNullable<LandingData["real"]> }) {
  const f = r.forecast;
  const people = r.datasets.reduce((a, d) => a + (isNum(d.n_people) ? d.n_people : 0), 0);
  const records = r.datasets.reduce((a, d) => a + (isNum(d.used_records) ? d.used_records : 0), 0);
  const risk = r.risk.find((e) => e.event === "ge180_2h") ?? r.risk[0];
  const s = r.synthetic_vs_real;
  return (
    <Reveal className="mx-auto mt-10 max-w-[1072px]">
      <div className="rounded-[28px] bg-[#1e1a19] p-7 text-white shadow-[var(--shadow-soft)] sm:p-9">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="text-[12px] font-semibold tracking-[0.12em] text-white/60 uppercase">Real-data validation</div>
          <span className="rounded-full bg-white/10 px-3 py-1 text-[11px] font-semibold tracking-wide">REAL · CGMacros + ShanghaiT2DM (non-commercial licence)</span>
        </div>
        <div className="mt-3 max-w-[760px] text-[22px] leading-snug font-bold tracking-[-0.03em] sm:text-[26px]">
          Then we ran the unchanged twin on {records} real CGM records from {people} people, with no tuning.
        </div>
        <div className="mt-7 grid gap-5 sm:grid-cols-3">
          {[
            ["Twin forecast RMSE, mg/dL", fmtList(f.twin.rmse), `+${f.horizons_min.join(" / +")} min · persistence ${fmtList(f.persistence.rmse)}`],
            ["Data-driven LightGBM (GlycoTwin)", fmtList(f.glycotwin_lgbm.rmse), `same ${isNum(f.n_points) ? f.n_points.toLocaleString("en-IN") : DASH} timestamps · linear ${fmtList(f.linear.rmse, 0)}`],
            [
              "≥180 within 2 h, AUROC",
              risk ? `${fmtList([risk.baseline.auroc], 3)} → ${fmtList([risk.plus_twin.auroc], 3)}` : DASH,
              risk ? `baseline → + twin features; synthetic model, no retraining: ${fmtList([risk.transfer_no_retrain.auroc], 3)}` : "",
            ],
          ].map(([a, b, c]) => (
            <div key={a} className="border-t border-white/15 pt-4">
              <div className="text-[13px] text-white/60">{a}</div>
              <div className="num mt-1.5 text-[22px] font-bold tracking-[-0.03em]">{b}</div>
              <div className="mt-1 text-[12.5px] text-white/55">{c}</div>
            </div>
          ))}
        </div>
        <p className="mt-6 text-[13.5px] leading-relaxed text-white/70">
          Honest reading: on real data the twin beats linear extrapolation and, at 2 h, persistence, but a data-driven forecaster is more accurate and the twin features add little. Our synthetic cohort is{" "}
          {isNum(s.event_rate_ratio_gt250) ? `${s.event_rate_ratio_gt250.toFixed(1)}×` : DASH} more prone to &gt;250 mg/dL events than these real records, so synthetic scores are not real-world performance.
        </p>
      </div>
    </Reveal>
  );
}

